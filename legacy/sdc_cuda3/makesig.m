function [sigint]=makesig(intord,varargin)
%
%  This routine returns the integration matrix for the IDC method 
%  
%   The optional input parameters in varargin correspond to
%
%   vargin{1} = whichpts
%   vargin{2} = Lopt
%
%   The flag whichpts determines which points to use
%   whichpts = 0  :  Gauss-Legendre
%   whichpts = 1  :  Gauss-Radau
%   whichpts = 2  :  Gauss-Labotto   (default)
%   whichpts = 3  :  Uniform
%
%  The flag Lopt determines how the left endpoint is used.
%  The matrix sigint has two possible parts
%      sigint(:,:,1) :  Uses the left endpoint
%      sigint(:,:,2) :  Does not use the left endpoint
%
%   Lopt = 0  - both parts are returned as above
%   Lopt = 1  - only the piece using the left endpoint is returned (default)
%   Lopt = 2  - only the piece not using the left endpoint is returned
%   Lopt = 3  - both parts are returned, but switched
%
%   Note  for Legendre and Radau, the left point is added for sigint(:,:,1) 
%   while for Labatto and Uniform, the left point is removed for sigint(:,:,2) 
%
%   intord refers to the minimum order of sigint(:,:,1:2), hence  
  %   if Lopt = 1, one fewer point is used than for Lopt = 0 or 2

switch nargin,
  case 1,
    whichpts = 2; % Default value
    Lopt = 1;     % Default value
  case 2,
    whichpts = varargin{1}; 
    Lopt = 1;     % Default value
  case 3,
    whichpts = varargin{1}; 
    Lopt = varargin{2};
  otherwise,
    error = 'makesig.m'
    pause
  end

 %  First compute the number of quadrature nodes needed to compute the
 %  integral ignoring the left endpoint.  For Guass-Legendre and Radau 
 %  this is just intord, but for Legendre and Radau, we need to ask for 
 %  one more because the input to qnodes is the number of quadrature nodes
 %  in the quadrature rule.  Then if Lopt = 1, we can subtract 1,
 %  Except for Legendre where we need an order more for extrap
 npoints = intord;  
 if (whichpts == 0)
    npoints = npoints+1;   % Need one more for interpolation
 end
 if (whichpts == 2 || whichpts == 3) 
    npoints = intord+1;  % Need one less point for Legendre, Radau
 end
 if (Lopt == 1 && whichpts ~= 0)
    npoints = npoints-1;  
 end

  %  Call a routine which returns the times
  stimes = qnodes(npoints,whichpts);

  sexp = stimes-0.5;
  simp = sexp(2:end);

% Explicit piece
nsdc = length(sexp);  nrad = length(sexp);

A = zeros(nrad,nsdc);
int = zeros(nsdc,nrad);

for i=1:nsdc
  % form K = prod(i!=j) (x-xj)
  [R,P,K] = residue(poly(sexp),poly([sexp(i)]));

  % compute prod(i!=j) (xi-xj) = K(xi)
  c = polyval(K,sexp(i));
  A(i,:) = K/c;             %  Coefficients of the ith Lagrangian poly
  int(i,:) = 1/i *sexp.^i;  %  Integral of monomials
end

intint = flipud(int(:,2:end)-int(:,1:end-1));
siginte = (A * intint)';

% Implicit piece
s = simp;
nsdc = length(s);
nrad = length(sexp);

A = zeros(nrad,nsdc);
int = zeros(nsdc,nrad);

for i=1:nsdc

  % form prod(i!=j) (x-xj)
  [R,P,K] = residue(poly(s),poly([s(i)]));

  % compute prod(i!=j) (xi-xj)
  c = polyval(K,s(i));
  A(i+1,:) = K/c;
  int(i,:) = 1/i * sexp.^i;
end

intint = flipud(int(:,2:end)-int(:,1:end-1));
siginti = (A * intint)';

switch Lopt
  case 0,
    sigint(:,:,1) = siginte;
    sigint(:,:,2) = siginti;
  case 1,
    sigint(:,:) = siginte;
  case 2,
    sigint(:,:) = siginti;
  case 3,
    sigint(:,:,2) = siginte;
    sigint(:,:,1) = siginti;
  otherwise
    error = 'makesig.m'
   pause
end

%save sigfile siginte siginti -ascii -double; pause;

%  Call a routine to check the integration
%[erre,erri] = sigmatcheck(sigint,whichpts);


clear siginte;
clear siginti;
clear int;
clear intint;
clear v;
clear c;
clear A;

