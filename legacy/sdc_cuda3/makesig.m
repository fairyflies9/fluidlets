function [erre,erri]=sigmatcheck(sigint,whichpts)

%  Routine to check the accuracy of the integration matrix
%
  siginte= squeeze(sigint(:,:,1));
  siginti= squeeze(sigint(:,:,2));
  t = cumsum(sum(siginte'));
  t = [0,t]

  erre = zeros(1,length(t));
  erri = zeros(1,length(t));

  % First  check the explicit piece
  %  First check the monomials of  order 0 to length(t)-1;
     for k = 1:length(t)
         pt = (0.25*t+1).^(k-1);      %  Polynomial evaluated at t
         ipt = 4/k*(0.25*t+1).^k;        % Integral of poly evaluated at t
         qex = ipt(2:end)-ipt(1:end-1); %  Exact Integral of subintervals
         q = siginte*pt';                 %  Estimates of integrals
         qerr = q-qex'; 	    
         erre(k) = max(abs(qerr)./abs(qex'));
     end

     %  Now check higher order monomials over whole domain
     if (whichpts == 1)
        nmax = 2*(length(t)-1)-1;  %  Radau 
     elseif (whichpts == 2)
        nmax = 2*(length(t)-1)-2;  %  Lobatto
     else
        nmax = 0;  %  Don't bother for uniform or Leg. or uniform
     end

     for k = length(t)+1:nmax;
         pt = (0.25*t+1).^(k-1);      %  Polynomial evaluated at t
         qex = 4/k*(0.25+1).^k - 4/k;  % Integral of poly evaluated at 1
         q = sum(siginte*pt');           %  Estimates of integrals
         qerr = q-qex';
         erre(k) = abs(qerr)/abs(qex); 	    
     end

  %  Now check the implicit piece
  %  First check the monomials of  order 0 to length(t)-2;
     for k = 1:length(t)-1
         pt = (0.25*t+1).^(k-1);      %  Polynomial evaluated at t
         ipt = 4/k*(0.25*t+1).^k;        % Integral of poly evaluated at t
         qex = ipt(2:end)-ipt(1:end-1); %  Exact Integral of subintervals
         q = siginti*pt';                 %  Estimates of integrals
         qerr = q-qex'; 	    
         erri(k) = max(abs(qerr)./abs(qex'));
     end

     %  Now check higher order monomials over whole domain
     if (whichpts == 1)
        nmax = 2*(length(t)-1)-1;  %  Radau 
     else
        nmax = 0;  %  Don't bother for uniform or Leg. or Lab. or uniform
     end

     for k = length(t):nmax;
         pt = (0.25*t+1).^(k-1);      %  Polynomial evaluated at t
         qex = 4/k*(0.25+1).^k - 4/k;  % Integral of poly evaluated at 1
         q = sum(siginti*pt');           %  Estimates of integrals
         qerr = q-qex';
         erri(k) = abs(qerr)/abs(qex); 	    
     end
     format long e
     erre
     erri
     format
     message = 'pausing in sigmatcheck'
     pause

